function normalizeLocale(value) {
  const normalized = String(value || "").trim().toLowerCase();
  if (/^zh(?:$|(?:[-_](?:hans|cn))(?:[._-]|$))/.test(normalized)) return "zh-CN";
  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  return null;
}

function parseCookies(cookieHeader = "") {
  const result = {};
  for (const part of String(cookieHeader || "").split(";")) {
    const index = part.indexOf("=");
    if (index < 1) continue;
    const name = part.slice(0, index).trim();
    const value = part.slice(index + 1).trim();
    if (name) result[name] = decodeURIComponent(value);
  }
  return result;
}

function browserLocale(browser) {
  const candidates = [...(browser.navigator?.languages || []), browser.navigator?.language];
  for (const candidate of candidates) {
    const locale = normalizeLocale(candidate);
    if (locale) return locale;
  }
  return "en";
}

function serverLocale(browser) {
  return normalizeLocale(browser.__CODEX_SUITE_CONFIG__?.locale) || "auto";
}

function cookieLocale(browser) {
  try {
    const cookie = parseCookies(browser.document?.cookie)[LOCALE_COOKIE_NAME];
    return cookie ? normalizeLocale(cookie) : null;
  } catch {
    return null;
  }
}

function urlLocale(browser) {
  try {
    return normalizeLocale(new URLSearchParams(browser.window?.location?.search || "").get("locale"));
  } catch {
    return null;
  }
}

function createI18n(browser) {
  const url = urlLocale(browser);
  const cookie = cookieLocale(browser);
  const server = serverLocale(browser);
  let currentLocale = url || cookie || (server === "auto" ? null : server) || browserLocale(browser);
  let currentMessages = messages[currentLocale] || messages.en;

  const translate = (key, values = {}) => {
    const template = currentMessages[key] ?? messages.en[key] ?? (key.startsWith("error.") ? key.slice(6) : key);
    return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
  };
  const persistLocale = (locale) => {
    if (browser.document) browser.document.cookie = `${LOCALE_COOKIE_NAME}=${encodeURIComponent(locale)}; path=/; max-age=31536000; SameSite=Lax`;
    if (browser.document?.documentElement) browser.document.documentElement.lang = locale;
  };
  const setLocale = (locale) => {
    const normalized = normalizeLocale(locale);
    if (!normalized || normalized === currentLocale) return;
    currentLocale = normalized;
    currentMessages = messages[currentLocale] || messages.en;
    persistLocale(currentLocale);
  };
  persistLocale(currentLocale);
  return {
    t: translate,
    getLocale: () => currentLocale,
    setLocale,
    isTranslatedKey: (key) => Object.hasOwn(currentMessages, key) || Object.hasOwn(messages.en, key),
  };
}

export function initI18nFactory(browser = globalThis) {
  return createI18n(browser);
}

export const initI18n = () => initI18nFactory(globalThis);
